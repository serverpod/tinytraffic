"""Scans the asset pack folders (`*-glb`) next to this viewer and writes manifest.js.

Run again after adding or removing assets:  python3 viewer/build_manifest.py
"""
import hashlib
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = Path(__file__).resolve().parent / "manifest.js"

# Files whose top-level nodes are separate, standalone objects (not parts of one model).
SPLIT_PACKS = {"Ultimate Stylized Nature Pack-glb"}
SPLIT_FILES = {"City Pack.undefined-glb/Road Bits.glb"}


def read_gltf_json(path):
    data = path.read_bytes()
    length = struct.unpack("<I", data[12:16])[0]
    return json.loads(data[20 : 20 + length])


def object_level(gltf):
    """Descends through single-child wrapper nodes; returns the node indices of the object level."""
    nodes = gltf["nodes"]
    level = gltf["scenes"][gltf.get("scene", 0)]["nodes"]
    while len(level) == 1 and nodes[level[0]].get("children"):
        level = nodes[level[0]]["children"]
    return level


def main():
    assets = []
    first_by_hash = {}
    for path in sorted(ROOT.glob("*-glb/*.glb"), key=lambda p: (p.parent.name, p.name.lower())):
        rel = f"{path.parent.name}/{path.name}"
        digest = hashlib.md5(path.read_bytes()).hexdigest()
        gltf = read_gltf_json(path)
        level = object_level(gltf)
        names = [gltf["nodes"][i].get("name", f"node{i}") for i in level]
        split = (path.parent.name in SPLIT_PACKS or rel in SPLIT_FILES) and len(level) > 1
        assets.append(
            {
                "path": rel,
                "pack": path.parent.name,
                "name": path.stem,
                "bytes": path.stat().st_size,
                "animations": [a.get("name", f"anim{i}") for i, a in enumerate(gltf.get("animations", []))],
                "rootName": names[0] if len(names) == 1 else None,
                "parts": names if split else None,
                "partNodes": level if split else None,
                "duplicateOf": first_by_hash.get(digest),
            }
        )
        first_by_hash.setdefault(digest, rel)
    OUT.write_text("// Generated by build_manifest.py — do not edit by hand.\nexport const ASSETS = "
                   + json.dumps(assets, indent=1) + ";\n")
    print(f"Wrote {len(assets)} assets to {OUT}")


if __name__ == "__main__":
    main()
